a=input('Digite algo: ')
n1=a.isnumeric()
n2=a.isalpha()
n3=a.islower()
n4=a.isdecimal()
n5=a.isspace()
n6=a.isupper()
n7=a.isalnum()
n8=a.istitle()
print('É só numero=',n1)
print('É só letras=',n2)
print('É só minusculos=',n3)
print('É decimal=',n4)
print('Tem espaços=',n5)
print('Só é maiusculos=',n6)
print('É alfanúmericos=',n7)
print('É capitalizado=',n8)